const header = "Code generated by api/gen from api/openapi.yaml. DO NOT EDIT."

// goTypes renders schemas as Go types. prefix qualifies the SDK package's
// names when the code lives outside it ("helm.").
type goTypes struct {
	d      *Doc
	prefix string
	inline map[string]*Schema // inline object schemas, named by where they appear
	order  []string
}

func newGoTypes(d *Doc, prefix string) *goTypes {
	return &goTypes{d: d, prefix: prefix, inline: map[string]*Schema{}}
}

func (g *goTypes) comp(name string) *Schema { return g.d.Schemas[name] }

func (g *goTypes) isAlias(name string) bool {
	s := g.comp(name)
	return s != nil && s.typ() == "string" && len(s.Enum) == 0
}

func (g *goTypes) isEnum(name string) bool {
	s := g.comp(name)
	return s != nil && s.typ() == "string" && len(s.Enum) > 0
}

// deref follows a component reference to its schema, or returns s.
func (g *goTypes) deref(s *Schema) *Schema {
	if s.Ref != "" {
		return g.comp(s.Ref)
	}
	return s
}

func (g *goTypes) typeOf(s *Schema, ctx string) string {
	if s.Ref != "" {
		switch {
		case s.Ref == "JSONObject":
			return "map[string]any"
		case s.Ref == "Error":
			return g.prefix + "Error"
		case g.isAlias(s.Ref):
			return "string"
		}
		return g.prefix + s.Ref
	}
	switch s.typ() {
	case "array":
		return "[]" + g.typeOf(s.Items, ctx+"Item")
	case "object":
		if len(s.Props) == 0 && len(s.AllOf) == 0 {
			return "map[string]any"
		}
		if _, ok := g.inline[ctx]; !ok {
			g.inline[ctx] = s
			g.order = append(g.order, ctx)
		}
		return g.prefix + ctx
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "string":
		if s.Format == "date-time" {
			return "time.Time"
		}
	}
	return "string"
}

// props flattens allOf into one property list and required set.
func (g *goTypes) props(s *Schema) ([]Prop, map[string]bool) {
	if len(s.AllOf) == 0 {
		return s.Props, s.Required
	}
	var out []Prop
	req := map[string]bool{}
	seen := map[string]bool{}
	for _, part := range s.AllOf {
		ps, r := g.props(g.deref(part))
		for _, p := range ps {
			if !seen[p.Name] {
				seen[p.Name] = true
				out = append(out, p)
			}
		}
		for k := range r {
			req[k] = true
		}
	}
	return out, req
}

type goField struct {
	Name, Type, Tag string
	Pointer         bool // Type is *T for a scalar or struct
	P               Prop
	Base            *Schema
}

func (g *goTypes) fields(ctx string, s *Schema) []goField {
	props, req := g.props(s)
	var out []goField
	for _, p := range props {
		base, isNull := nullable(p.S)
		t := g.typeOf(base, ctx+goName(p.Name))
		coll := strings.HasPrefix(t, "[]") || strings.HasPrefix(t, "map[")
		f := goField{Name: goName(p.Name), Tag: p.Name, P: p, Base: base}
		switch {
		case req[p.Name] && !isNull:
		case req[p.Name]:
			if !coll {
				t, f.Pointer = "*"+t, true
			}
		default:
			if !coll {
				t, f.Pointer = "*"+t, true
			}
			f.Tag += ",omitempty"
		}
		f.Type = t
		out = append(out, f)
	}
	return out
}

// reachable returns the component schemas studio-api operations use.
func reachable(d *Doc) map[string]bool {
	seen := map[string]bool{}
	var walk func(s *Schema)
	walk = func(s *Schema) {
		if s == nil {
			return
		}
		if s.Ref != "" {
			if !seen[s.Ref] {
				seen[s.Ref] = true
				walk(d.Schemas[s.Ref])
			}
			return
		}
		walk(s.Items)
		for _, p := range s.Props {
			walk(p.S)
		}
		for _, x := range append(append([]*Schema{}, s.AllOf...), s.OneOf...) {
			walk(x)
		}
	}
	for _, op := range d.Ops {
		if !op.studio() {
			continue
		}
		for _, p := range op.Params {
			walk(p.S)
		}
		walk(op.Body)
		for _, r := range op.Success {
			walk(r.S)
		}
		for _, e := range op.Events {
			walk(e.S)
		}
	}
	seen["Error"] = true
	return seen
}

func comment(b *strings.Builder, indent, text string) {
	text = strings.Join(strings.Fields(text), " ")
	if text == "" {
		return
	}
	line := indent + "//"
	for _, w := range strings.Fields(text) {
		if len(line)+1+len(w) > 88 && line != indent+"//" {
			b.WriteString(line + "\n")
			line = indent + "//"
		}
		line += " " + w
	}
	b.WriteString(line + "\n")
}

func constName(typeName, value string) string { return typeName + goName(value) }

// ---------------------------------------------------------------- SDK types

func genGoTypes(d *Doc) string {
	g := newGoTypes(d, "")
	used := reachable(d)
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage helm\n\nimport \"time\"\n\nvar _ = time.Time{}\n\n", header)
	fmt.Fprintf(&b, "// APIVersion is info.version of the contract these types were generated from.\nconst APIVersion = %q\n\n", d.Version)

	emitStruct := func(name string, s *Schema) {
		structDoc(&b, name, s.Description)
		fmt.Fprintf(&b, "type %s struct {\n", name)
		for _, f := range g.fields(name, s) {
			comment(&b, "\t", f.P.S.Description)
			fmt.Fprintf(&b, "\t%s %s `json:\"%s\"`\n", f.Name, f.Type, f.Tag)
		}
		b.WriteString("}\n\n")
	}
	for _, name := range d.SchemaKeys {
		if !used[name] || name == "JSONObject" || name == "Error" || g.isAlias(name) {
			continue
		}
		s := d.Schemas[name]
		if g.isEnum(name) {
			structDoc(&b, name, s.Description)
			fmt.Fprintf(&b, "type %s string\n\nconst (\n", name)
			for _, v := range s.Enum {
				fmt.Fprintf(&b, "\t%s %s = %q\n", constName(name, v), name, v)
			}
			b.WriteString(")\n\n")
			continue
		}
		emitStruct(name, s)
	}
	// Parameter structs, then inline objects discovered along the way.
	for _, op := range d.Ops {
		if !op.studio() {
			continue
		}
		ps := op.paramsIn("query", "header")
		if len(ps) == 0 {
			continue
		}
		name := paramsName(op)
		fmt.Fprintf(&b, "// %s holds the query and header parameters of %s %s.\ntype %s struct {\n", name, op.Verb, op.Path, name)
		for _, p := range ps {
			t := g.typeOf(p.S, name+goName(p.Name))
			if !p.Required && !strings.HasPrefix(t, "[]") {
				t = "*" + t
			}
			fmt.Fprintf(&b, "\t%s %s\n", goName(p.Name), t)
		}
		b.WriteString("}\n\n")
	}
	for i := 0; i < len(g.order); i++ {
		name := g.order[i]
		emitStruct(name, g.inline[name])
	}
	return b.String()
}

func paramsName(op *Op) string { return goName(op.Group) + goName(op.Method) + "Params" }

// ---------------------------------------------------------------- SDK client

type goSig struct {
	args     []string // after ctx
	callArgs []string
	results  string
}

func (g *goTypes) bodyType(op *Op) string {
	switch {
	case op.Body == nil:
		return ""
	case op.BodyType == "application/json" && op.Body.Ref != "JSONObject":
		return g.typeOf(op.Body, "")
	case op.BodyType == "application/json" || op.BodyType == "application/merge-patch+json":
		return "map[string]any"
	}
	return "io.Reader"
}

func (g *goTypes) resultType(op *Op) string {
	if r := op.result(); r != nil && op.kind() == "json" {
		return "*" + g.typeOf(r.S, "")
	}
	return ""
}

func (g *goTypes) clientSig(op *Op) goSig {
	var s goSig
	for _, p := range op.paramsIn("path") {
		s.args = append(s.args, camel(p.Name)+" string")
		s.callArgs = append(s.callArgs, camel(p.Name))
	}
	if bt := g.bodyType(op); bt != "" {
		s.args = append(s.args, "body "+bt)
		s.callArgs = append(s.callArgs, "body")
		if bt == "io.Reader" {
			s.args = append(s.args, "contentType string")
			s.callArgs = append(s.callArgs, "contentType")
		}
	}
	if len(op.paramsIn("query", "header")) > 0 {
		s.args = append(s.args, "params *"+g.prefix+paramsName(op))
		s.callArgs = append(s.callArgs, "params")
	}
	switch op.kind() {
	case "json":
		s.results = "(" + g.resultType(op) + ", error)"
	case "raw":
		s.results = "(*" + g.prefix + "RawResponse, error)"
	case "sse":
		s.results = "(*" + g.prefix + "EventStream, error)"
	default:
		s.results = "error"
	}
	return s
}

func groups(d *Doc) []string {
	var out []string
	seen := map[string]bool{}
	for _, op := range d.Ops {
		if op.studio() && !seen[op.Group] {
			seen[op.Group] = true
			out = append(out, op.Group)
		}
	}
	return out
}

func opsOf(d *Doc, group string) []*Op {
	var out []*Op
	for _, op := range d.Ops {
		if op.studio() && op.Group == group {
			out = append(out, op)
		}
	}
	return out
}

// pathExpr renders the request path as a Go string expression.
func pathExpr(op *Op, escape func(string) string) string {
	var parts []string
	lit := ""
	rest := op.Path
	for rest != "" {
		i := strings.Index(rest, "{")
		if i < 0 {
			lit += rest
			break
		}
		lit += rest[:i]
		j := strings.Index(rest, "}")
		parts = append(parts, strconv.Quote(lit), escape(camel(rest[i+1:j])))
		lit = ""
		rest = rest[j+1:]
	}
	if lit != "" {
		parts = append(parts, strconv.Quote(lit))
	}
	return strings.Join(parts, " + ")
}

func (g *goTypes) formatQuery(expr string, s *Schema) string {
	t := g.typeOf(s, "")
	switch {
	case t == "int64":
		return "strconv.FormatInt(" + expr + ", 10)"
	case t == "float64":
		return "strconv.FormatFloat(" + expr + ", 'g', -1, 64)"
	case t == "bool":
		return "strconv.FormatBool(" + expr + ")"
	case t == "time.Time":
		return expr + ".Format(time.RFC3339Nano)"
	case t == "string":
		return expr
	}
	return "string(" + expr + ")"
}

func genGoClient(d *Doc) string {
	g := newGoTypes(d, "")
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage helm\n\nimport (\n\t\"context\"\n\t\"io\"\n\t\"net/http\"\n\t\"net/url\"\n\t\"strconv\"\n\t\"time\"\n)\n\n", header)
	b.WriteString("var (\n\t_ = io.EOF\n\t_ = strconv.Itoa\n\t_ = time.RFC3339\n)\n\n")

	b.WriteString("// Client is the runtime SDK: one field per API group, the same names in Go,\n// Python and Node (docs/design/04-packages.md §4). Every provider fills the same\n// interfaces.\ntype Client struct {\n")
	for _, grp := range groups(d) {
		fmt.Fprintf(&b, "\t%s %sAPI\n", goName(grp), goName(grp))
	}
	b.WriteString("}\n\n")

	for _, grp := range groups(d) {
		gn := goName(grp)
		fmt.Fprintf(&b, "// %sAPI is the %s group.\ntype %sAPI interface {\n", gn, grp, gn)
		for _, op := range opsOf(d, grp) {
			sig := g.clientSig(op)
			comment(&b, "\t", goName(op.Method)+": "+op.Summary+" ("+op.Verb+" "+op.Path+")")
			fmt.Fprintf(&b, "\t%s(%s) %s\n", goName(op.Method), strings.Join(append([]string{"ctx context.Context"}, sig.args...), ", "), sig.results)
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("func newClient(t *transport) *Client {\n\treturn &Client{\n")
	for _, grp := range groups(d) {
		fmt.Fprintf(&b, "\t\t%s: %sRemote{t},\n", goName(grp), camel(grp))
	}
	b.WriteString("\t}\n}\n\n")

	for _, grp := range groups(d) {
		fmt.Fprintf(&b, "type %sRemote struct{ t *transport }\n\n", camel(grp))
		for _, op := range opsOf(d, grp) {
			sig := g.clientSig(op)
			fmt.Fprintf(&b, "func (g %sRemote) %s(%s) %s {\n", camel(grp), goName(op.Method),
				strings.Join(append([]string{"ctx context.Context"}, sig.args...), ", "), sig.results)
			b.WriteString("\tq := url.Values{}\n\th := http.Header{}\n")
			if ps := op.paramsIn("query", "header"); len(ps) > 0 {
				b.WriteString("\tif params != nil {\n")
				for _, p := range ps {
					f := "params." + goName(p.Name)
					t := g.typeOf(p.S, "")
					set := "q.Add"
					key := p.Name
					if p.In == "header" {
						set = "h.Set"
					}
					switch {
					case strings.HasPrefix(t, "[]"):
						fmt.Fprintf(&b, "\t\tfor _, v := range %s {\n\t\t\t%s(%q, %s)\n\t\t}\n", f, set, key, g.formatQuery("v", p.S.Items))
					case p.Required:
						fmt.Fprintf(&b, "\t\t%s(%q, %s)\n", set, key, g.formatQuery(f, p.S))
					default:
						fmt.Fprintf(&b, "\t\tif %s != nil {\n\t\t\t%s(%q, %s)\n\t\t}\n", f, set, key, g.formatQuery("(*"+f+")", p.S))
					}
				}
				b.WriteString("\t}\n")
			}
			path := pathExpr(op, func(v string) string { return "url.PathEscape(" + v + ")" })
			bt := g.bodyType(op)
			switch bt {
			case "":
				fmt.Fprintf(&b, "\tresp, err := g.t.do(ctx, %q, %s, q, h, nil, \"\")\n", op.Verb, path)
			case "io.Reader":
				fmt.Fprintf(&b, "\tresp, err := g.t.do(ctx, %q, %s, q, h, body, contentType)\n", op.Verb, path)
			default:
				fmt.Fprintf(&b, "\trd, err := encodeJSON(body)\n\tif err != nil {\n\t\treturn %s\n\t}\n", zeroReturn(op, "err"))
				fmt.Fprintf(&b, "\tresp, err := g.t.do(ctx, %q, %s, q, h, rd, %q)\n", op.Verb, path, op.BodyType)
			}
			fmt.Fprintf(&b, "\tif err != nil {\n\t\treturn %s\n\t}\n", zeroReturn(op, "err"))
			switch op.kind() {
			case "json":
				fmt.Fprintf(&b, "\treturn decodeJSON[%s](resp)\n", strings.TrimPrefix(g.resultType(op), "*"))
			case "raw":
				b.WriteString("\treturn newRawResponse(resp), nil\n")
			case "sse":
				b.WriteString("\treturn newEventStream(resp), nil\n")
			default:
				b.WriteString("\treturn drain(resp)\n")
			}
			b.WriteString("}\n\n")
		}
	}
	return b.String()
}

func zeroReturn(op *Op, err string) string {
	if op.kind() == "empty" {
		return err
	}
	return "nil, " + err
}

// ---------------------------------------------------------------- server

func genGoServer(d *Doc) string {
	g := newGoTypes(d, "helm.")
	v := &validators{g: g, done: map[string]bool{}}
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage studioapi\n\nimport (\n\t\"context\"\n\t\"io\"\n\t\"net/http\"\n\t\"regexp\"\n\t\"strconv\"\n\t\"time\"\n\n\thelm \"github.com/janishar/helmstudio/packages/helm-runtime-sdk/go\"\n)\n\n", header)
	b.WriteString("var (\n\t_ = io.EOF\n\t_ = strconv.Itoa\n\t_ = time.RFC3339\n\t_ = regexp.MustCompile\n)\n\n")

	b.WriteString("// Server is every studio-api operation. It is implemented once, by Service,\n// and the same router serves it to the daemon and to the embedded provider.\ntype Server interface {\n")
	for _, op := range d.Ops {
		if op.studio() {
			fmt.Fprintf(&b, "\t%s(%s) %s\n", goName(op.ID), strings.Join(serverArgs(g, op), ", "), serverResults(g, op))
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("var routes = []route{\n")
	for _, op := range d.Ops {
		if !op.studio() {
			continue
		}
		fmt.Fprintf(&b, "\t{method: %q, path: %q, operation: %q, capability: %q, serve: serve%s},\n", op.Verb, op.Path, op.ID, op.Cap, goName(op.ID))
	}
	b.WriteString("}\n\n")

	for _, op := range d.Ops {
		if !op.studio() {
			continue
		}
		fmt.Fprintf(&b, "func serve%s(ctx context.Context, h *Handler, w http.ResponseWriter, r *http.Request, pv []string) {\n", goName(op.ID))
		var call []string
		call = append(call, "ctx")
		if k := op.kind(); k == "raw" || k == "sse" {
			call = append(call, "w", "r")
		}
		for i, p := range op.paramsIn("path") {
			name := camel(p.Name)
			fmt.Fprintf(&b, "\t%s := pv[%d]\n", name, i)
			if check := v.scalarCheck(strconv.Quote(p.Name), name, p.S); check != "" {
				fmt.Fprintf(&b, "\tif err := %s; err != nil {\n\t\th.fail(w, r, err)\n\t\treturn\n\t}\n", check)
			}
			call = append(call, name)
		}
		switch bt := g.bodyType(op); bt {
		case "":
		case "io.Reader":
			call = append(call, "r.Body", "r.Header.Get(\"Content-Type\")", "r.ContentLength")
		case "map[string]any":
			allowed := "nil"
			if s := g.deref(op.Body); op.Body.Ref != "JSONObject" && s != nil && s.Closed {
				props, _ := g.props(s)
				var names []string
				for _, p := range props {
					names = append(names, strconv.Quote(p.Name))
				}
				allowed = "[]string{" + strings.Join(names, ", ") + "}"
			}
			minProps := int64(0)
			if s := g.deref(op.Body); s != nil && s.MinProps != nil {
				minProps = *s.MinProps
			}
			fmt.Fprintf(&b, "\tbody := map[string]any{}\n\tif err := readObject(w, r, &body, %s, %d); err != nil {\n\t\th.fail(w, r, err)\n\t\treturn\n\t}\n", allowed, minProps)
			call = append(call, "body")
		default:
			s := g.deref(op.Body)
			_, req := g.props(s)
			var names []string
			for k := range req {
				names = append(names, strconv.Quote(k))
			}
			sort.Strings(names)
			fmt.Fprintf(&b, "\tvar body %s\n\tif err := readBody(w, r, &body, []string{%s}); err != nil {\n\t\th.fail(w, r, err)\n\t\treturn\n\t}\n", bt, strings.Join(names, ", "))
			fmt.Fprintf(&b, "\tif err := %s(&body); err != nil {\n\t\th.fail(w, r, err)\n\t\treturn\n\t}\n", v.structValidator(op.Body.Ref, s))
			call = append(call, "&body")
		}
		if ps := op.paramsIn("query", "header"); len(ps) > 0 {
			fmt.Fprintf(&b, "\tvar params helm.%s\n", paramsName(op))
			if len(op.paramsIn("query")) > 0 {
				b.WriteString("\tquery := r.URL.Query()\n")
			}
			for _, p := range ps {
				field := "params." + goName(p.Name)
				get := fmt.Sprintf("query[%q]", p.Name)
				if p.In == "header" {
					get = fmt.Sprintf("r.Header.Values(%q)", p.Name)
				}
				t := g.typeOf(p.S, "")
				if strings.HasPrefix(t, "[]") {
					fmt.Fprintf(&b, "\t%s = %s\n", field, get)
					if p.S.MaxItems != nil {
						fmt.Fprintf(&b, "\tif len(%s) > %d {\n\t\th.fail(w, r, badParam(%q, \"at most %d values\"))\n\t\treturn\n\t}\n", field, *p.S.MaxItems, p.Name, *p.S.MaxItems)
					}
					if check := v.scalarCheck(strconv.Quote(p.Name), "x", p.S.Items); check != "" {
						fmt.Fprintf(&b, "\tfor _, x := range %s {\n\t\tif err := %s; err != nil {\n\t\t\th.fail(w, r, err)\n\t\t\treturn\n\t\t}\n\t}\n", field, check)
					}
					continue
				}
				fmt.Fprintf(&b, "\tif vs := %s; len(vs) > 0 {\n", get)
				parse, parsed := parseExpr(t, p.Name)
				b.WriteString(parse)
				if check := v.scalarCheck(strconv.Quote(p.Name), parsed, p.S); check != "" {
					fmt.Fprintf(&b, "\t\tif err := %s; err != nil {\n\t\t\th.fail(w, r, err)\n\t\t\treturn\n\t\t}\n", check)
				}
				if p.Required {
					fmt.Fprintf(&b, "\t\t%s = %s\n", field, parsed)
				} else {
					fmt.Fprintf(&b, "\t\t%s = &%s\n", field, parsed)
				}
				b.WriteString("\t}")
				if p.Required {
					fmt.Fprintf(&b, " else {\n\t\th.fail(w, r, badParam(%q, \"is required\"))\n\t\treturn\n\t}", p.Name)
				}
				b.WriteString("\n")
			}
			call = append(call, "params")
		}
		invoke := fmt.Sprintf("h.srv.%s(%s)", goName(op.ID), strings.Join(call, ", "))
		switch op.kind() {
		case "json":
			res := op.result()
			multi := len(op.statuses()) > 1
			if multi {
				fmt.Fprintf(&b, "\tres, created, err := %s\n", invoke)
			} else {
				fmt.Fprintf(&b, "\tres, err := %s\n", invoke)
			}
			b.WriteString("\tif err != nil {\n\t\th.fail(w, r, err)\n\t\treturn\n\t}\n")
			if res.ETag {
				b.WriteString("\tsetETag(w, res.ETag)\n")
			}
			if multi {
				b.WriteString("\tstatus := http.StatusOK\n\tif created {\n\t\tstatus = http.StatusCreated\n\t}\n\twriteJSON(w, status, res)\n")
			} else {
				fmt.Fprintf(&b, "\twriteJSON(w, %d, res)\n", res.Status)
			}
		case "empty":
			fmt.Fprintf(&b, "\tif err := %s; err != nil {\n\t\th.fail(w, r, err)\n\t\treturn\n\t}\n\tw.WriteHeader(%d)\n", invoke, op.Success[0].Status)
		default:
			fmt.Fprintf(&b, "\tif err := %s; err != nil {\n\t\th.fail(w, r, err)\n\t}\n", invoke)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString(v.out.String())
	return b.String()
}

func serverArgs(g *goTypes, op *Op) []string {
	args := []string{"ctx context.Context"}
	if k := op.kind(); k == "raw" || k == "sse" {
		args = append(args, "w http.ResponseWriter", "r *http.Request")
	}
	for _, p := range op.paramsIn("path") {
		args = append(args, camel(p.Name)+" string")
	}
	switch bt := g.bodyType(op); bt {
	case "":
	case "io.Reader":
		args = append(args, "body io.Reader", "contentType string", "contentLength int64")
	case "map[string]any":
		args = append(args, "body map[string]any")
	default:
		args = append(args, "body *"+bt)
	}
	if len(op.paramsIn("query", "header")) > 0 {
		args = append(args, "params helm."+paramsName(op))
	}
	return args
}

func serverResults(g *goTypes, op *Op) string {
	switch op.kind() {
	case "json":
		if len(op.statuses()) > 1 {
			return "(" + g.resultType(op) + ", bool, error)"
		}
		return "(" + g.resultType(op) + ", error)"
	}
	return "error"
}

func parseExpr(t, name string) (code, value string) {
	v := "v_" + snake(name)
	fail := fmt.Sprintf("\t\tif err != nil {\n\t\t\th.fail(w, r, badParam(%q, %%q))\n\t\t\treturn\n\t\t}\n", name)
	switch t {
	case "int64":
		return fmt.Sprintf("\t\t%s, err := strconv.ParseInt(vs[0], 10, 64)\n", v) + fmt.Sprintf(fail, "must be an integer"), v
	case "float64":
		return fmt.Sprintf("\t\t%s, err := strconv.ParseFloat(vs[0], 64)\n", v) + fmt.Sprintf(fail, "must be a number"), v
	case "bool":
		return fmt.Sprintf("\t\t%s, err := strconv.ParseBool(vs[0])\n", v) + fmt.Sprintf(fail, "must be true or false"), v
	case "time.Time":
		return fmt.Sprintf("\t\t%s, err := time.Parse(time.RFC3339Nano, vs[0])\n", v) + fmt.Sprintf(fail, "must be an RFC 3339 time"), v
	case "string":
		return fmt.Sprintf("\t\t%s := vs[0]\n", v), v
	}
	return fmt.Sprintf("\t\t%s := %s(vs[0])\n", v, t), v
}

// validators emits the checks the contract's schemas state, so both providers
// refuse the same malformed requests with the same 400.
type validators struct {
	g       *goTypes
	out     strings.Builder
	done    map[string]bool
	regexps int
}

func (v *validators) regexp(pattern string) string {
	name := fmt.Sprintf("pattern%d", v.regexps)
	v.regexps++
	fmt.Fprintf(&v.out, "var %s = regexp.MustCompile(%q)\n\n", name, pattern)
	return name
}

// scalarCheck returns an expression of type error checking one string,
// integer or number, or "" when the schema states nothing to check.
func (v *validators) scalarCheck(field, expr string, s *Schema) string {
	if s == nil {
		return ""
	}
	if s.Ref != "" {
		c := v.g.comp(s.Ref)
		switch {
		case v.g.isEnum(s.Ref):
			return fmt.Sprintf("checkEnum(%s, string(%s), %s)", field, expr, quoteList(c.Enum))
		case v.g.isAlias(s.Ref):
			return v.scalarCheck(field, expr, c)
		}
		return ""
	}
	switch v.g.typeOf(s, "") {
	case "string":
		var checks []string
		if s.Pattern != "" {
			checks = append(checks, fmt.Sprintf("checkPattern(%s, %s, %s)", field, expr, v.regexp(s.Pattern)))
		}
		if s.MinLength != nil || s.MaxLength != nil {
			checks = append(checks, fmt.Sprintf("checkLength(%s, %s, %d, %d)", field, expr, orInt(s.MinLength, -1), orInt(s.MaxLength, -1)))
		}
		if len(s.Enum) > 0 {
			checks = append(checks, fmt.Sprintf("checkEnum(%s, %s, %s)", field, expr, quoteList(s.Enum)))
		}
		if s.Const != "" {
			checks = append(checks, fmt.Sprintf("checkEnum(%s, %s, []string{%q})", field, expr, s.Const))
		}
		return joinChecks(checks)
	case "int64", "float64":
		if s.Minimum == nil && s.Maximum == nil && s.ExclMinimum == nil && len(s.Enum) == 0 {
			return ""
		}
		var checks []string
		if s.Minimum != nil || s.Maximum != nil || s.ExclMinimum != nil {
			checks = append(checks, fmt.Sprintf("checkRange(%s, float64(%s), %s, %s, %s)", field, expr, floatPtr(s.Minimum), floatPtr(s.Maximum), floatPtr(s.ExclMinimum)))
		}
		if len(s.Enum) > 0 {
			checks = append(checks, fmt.Sprintf("checkEnum(%s, strconv.FormatFloat(float64(%s), 'g', -1, 64), %s)", field, expr, quoteList(s.Enum)))
		}
		return joinChecks(checks)
	}
	return ""
}

func (v *validators) structValidator(name string, s *Schema) string {
	fn := "validate" + name
	if v.done[fn] {
		return fn
	}
	v.done[fn] = true
	var body strings.Builder
	for _, f := range v.g.fields(name, s) {
		field := strconv.Quote(f.P.Name)
		access := "v." + f.Name
		base := f.Base
		t := strings.TrimPrefix(f.Type, "*")
		wrap := func(check string) {
			if check == "" {
				return
			}
			if f.Pointer {
				fmt.Fprintf(&body, "\tif %s != nil {\n\t\tif err := %s; err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", access, strings.ReplaceAll(check, "\x00", "(*"+access+")"))
			} else {
				fmt.Fprintf(&body, "\tif err := %s; err != nil {\n\t\treturn err\n\t}\n", strings.ReplaceAll(check, "\x00", access))
			}
		}
		switch {
		case strings.HasPrefix(t, "[]"):
			if base.MinItems != nil || base.MaxItems != nil {
				fmt.Fprintf(&body, "\tif err := checkItems(%s, len(%s), %d, %d); err != nil {\n\t\treturn err\n\t}\n", field, access, orInt(base.MinItems, -1), orInt(base.MaxItems, -1))
			}
			item := base.Items
			if item.Ref != "" && !v.g.isAlias(item.Ref) && !v.g.isEnum(item.Ref) && item.Ref != "JSONObject" {
				fn := v.structValidator(item.Ref, v.g.comp(item.Ref))
				fmt.Fprintf(&body, "\tfor i := range %s {\n\t\tif err := %s(&%s[i]); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", access, fn, access)
			} else if check := v.scalarCheck(field, "x", item); check != "" {
				fmt.Fprintf(&body, "\tfor _, x := range %s {\n\t\tif err := %s; err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", access, check)
			}
		case strings.HasPrefix(t, "map["), t == "time.Time", t == "bool":
		case base.Ref != "" && !v.g.isAlias(base.Ref) && !v.g.isEnum(base.Ref):
			fn := v.structValidator(base.Ref, v.g.comp(base.Ref))
			if f.Pointer {
				fmt.Fprintf(&body, "\tif %s != nil {\n\t\tif err := %s(%s); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", access, fn, access)
			} else {
				fmt.Fprintf(&body, "\tif err := %s(&%s); err != nil {\n\t\treturn err\n\t}\n", fn, access)
			}
		case base.Ref == "" && base.typ() == "object" && len(base.Props) > 0:
			inline := strings.TrimPrefix(t, "helm.")
			fn := v.structValidator(inline, base)
			fmt.Fprintf(&body, "\tif %s != nil {\n\t\tif err := %s(%s); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", access, fn, access)
		default:
			wrap(v.scalarCheck(field, "\x00", base))
		}
	}
	fmt.Fprintf(&v.out, "func %s(v *helm.%s) error {\n%s\treturn nil\n}\n\n", fn, name, body.String())
	return fn
}

func orInt(p *int64, def int64) int64 {
	if p == nil {
		return def
	}
	return *p
}

func floatPtr(p *float64) string {
	if p == nil {
		return "nil"
	}
	return fmt.Sprintf("ptrFloat(%v)", *p)
}

func quoteList(vs []string) string {
	var q []string
	for _, v := range vs {
		q = append(q, strconv.Quote(v))
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func joinChecks(checks []string) string {
	switch len(checks) {
	case 0:
		return ""
	case 1:
		return checks[0]
	}
	return "firstError(" + strings.Join(checks, ", ") + ")"
}

func structDoc(b *strings.Builder, name, desc string) {
	if strings.TrimSpace(desc) == "" {
		fmt.Fprintf(b, "// %s is components.schemas.%s in api/openapi.yaml.\n", name, name)
		return
	}
	comment(b, "", name+": "+desc)
}
